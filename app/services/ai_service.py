def _build_few_shot_block() -> str:
    if not FEW_SHOT_EXAMPLES:
        return ""

    lines = ["ПРИМЕРЫ ЭТАЛОННОГО РЕЗУЛЬТАТА (строго следуй этому уровню детализации):"]
    for i, (user_input, result) in enumerate(FEW_SHOT_EXAMPLES, 1):
        lines.append(f"\n--- Пример {i} ---")
        lines.append(f"Вход: {user_input}")
        lines.append(f"Результат: {result}")
    return "\n".join(lines)


